"""Spell circles -> sphere glyphs.

A spell is a set of chords between 11 points on a circle (examples/spells/spells.json).
Here the 11 points move onto the sphere, at the 11-point Tammes optimum: a regular
icosahedron with one vertex removed (min separation 63.4349 deg, 25 contacts).

Mapping ("hub at the pole"):
    circle 5        -> north pole; it joins 0-4 in every spell, so that shared base
                       becomes five spokes from the pole
    circle 0-4      -> upper ring (z = +1/sqrt5), azimuth -90 + 72*i deg
    circle 6-10     -> lower ring (z = -1/sqrt5), azimuth -54 + 72*(i-6) deg
    (removed vertex -> south pole: the empty cap, which Lambert projects to the rim)

Each chord becomes a great-circle arc on the surface, the short way round. Antipodal
pairs (upper i, lower 6 + (i+2) % 5) have no unique great circle; they're routed over
the north pole. The arc is sampled here and written into the Substance as data, so the
Style only projects and inks it.

usage: python3 src/spells.py examples/spells/spells.json examples/spells
"""
import json
import math
import os
import sys

import numpy as np

N = 11
HUB = 5
SAMPLES = 5  # interior points per arc


def sphere11():
    """The 11 points, indexed by circle position."""
    z = 1 / math.sqrt(5)
    r = 2 / math.sqrt(5)
    x = np.zeros((N, 3))
    x[HUB] = (0.0, 0.0, 1.0)
    for i in range(5):
        a = math.radians(-90 + 72 * i)
        x[i] = (r * math.cos(a), r * math.sin(a), z)
    for i in range(6, 11):
        a = math.radians(-54 + 72 * (i - 6))
        x[i] = (r * math.cos(a), r * math.sin(a), -z)
    return x


def contacts(x, tol=1e-6):
    d = np.linalg.norm(x[:, None] - x[None], axis=-1)
    dmin = min(d[i, j] for i in range(len(x)) for j in range(i + 1, len(x)))
    return [(i, j) for i in range(len(x)) for j in range(i + 1, len(x)) if d[i, j] < dmin + tol]


def arc(a, b, k=SAMPLES):
    """k interior points along the short great-circle arc a -> b."""
    s = a + b
    if np.linalg.norm(s) < 1e-9:                    # antipodal: go over the north pole
        north = np.array([0.0, 0.0, 1.0])
        m = north - (north @ a) * a
        m /= np.linalg.norm(m)
        return [math.cos(math.pi * t) * a + math.sin(math.pi * t) * m
                for t in np.linspace(0, 1, k + 2)[1:-1]]
    w = math.acos(float(np.clip(a @ b, -1, 1)))
    return [(math.sin((1 - t) * w) * a + math.sin(t * w) * b) / math.sin(w)
            for t in np.linspace(0, 1, k + 2)[1:-1]]


def oriented(edge):
    """Stroke direction: out from the hub, otherwise from the lower circle index."""
    a, b = edge
    if b == HUB or (a != HUB and a > b):
        a, b = b, a
    return a, b


def literals(values, step=1e-6):
    """Format numbers for one Substance statement, all distinct in value.

    Penrose binds the `Number` variables of a Style `forall` injectively, so a statement
    like At(v, 0, 0, 1), with two equal literals, never matches and the vertex silently
    disappears. Nudge repeats by 1e-6 (~0.0002 px on the page) until every value is unique.
    """
    seen, out = set(), []
    for v in values:
        s = f"{v:.6f}"
        while float(s) in seen:
            v += step
            s = f"{v:.6f}"
        seen.add(float(s))
        out.append(s)
    return ", ".join(out)


def substance(spell, x):
    names = [f"v{i:02d}" for i in range(N)]
    lines = [
        f"-- name: {spell['name']}",
        "-- generated by spells.py from examples/spells/spells.json",
        f"-- level {spell['level']}, {spell['school']}, {spell['damage_type']}, "
        f"area {spell['area_type']}, range {spell['range']}",
        "",
        "Vertex " + ", ".join(names),
        "",
    ]
    lines += [f"At({names[i]}, {literals(p)})" for i, p in enumerate(x)]
    lines.append("")
    lines += [f"Contact({names[a]}, {names[b]})" for a, b in contacts(x)]
    lines.append("")
    if spell.get("mark") is not None:
        lines.append(f"Mark({names[spell['mark']]})")
    for e in spell["edges"]:
        a, b = oriented(e)
        pts = literals([c for p in arc(x[a], x[b]) for c in p])
        lines.append(f"Link({names[a]}, {names[b]}, {pts})")
    return "\n".join(lines) + "\n"


def main(src, outdir):
    with open(src) as fh:
        spells = json.load(fh)["spells"]
    x = sphere11()
    os.makedirs(outdir, exist_ok=True)
    for s in spells:
        with open(os.path.join(outdir, f"{s['slug']}.substance"), "w", newline="\n") as fh:
            fh.write(substance(s, x))
    print(f"wrote {len(spells)} spell substances to {outdir}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
