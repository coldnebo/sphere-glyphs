"""Turn a Tammes configuration into Penrose Substance programs, one per glyph.

A glyph is a Hamiltonian path through the contact graph: every vertex visited once,
moving only along minimum-distance edges. Paths related by a symmetry of the point
configuration (rotation/reflection) or by reversal are counted as the same glyph.

usage: python3 src/glyphs.py examples/tammes13.json examples/glyphs [max_glyphs]
"""
import itertools
import json
import os
import sys

import numpy as np


def largest_hole(x, samples=200_000, seed=1):
    """Direction on the sphere farthest from every vertex (centre of the biggest empty cap)."""
    rng = np.random.default_rng(seed)
    d = rng.normal(size=(samples, 3))
    d /= np.linalg.norm(d, axis=1, keepdims=True)
    score = (d @ x.T).max(axis=1)          # cos of angle to nearest vertex
    return d[np.argmin(score)]


def rotation_to_south(u):
    """Rotation matrix sending unit vector u to (0, 0, -1)."""
    t = np.array([0.0, 0.0, -1.0])
    v = np.cross(u, t)
    c = float(u @ t)
    if np.linalg.norm(v) < 1e-12:
        return np.eye(3) if c > 0 else np.diag([1.0, -1.0, -1.0])
    vx = np.array([[0, -v[2], v[1]], [v[2], 0, -v[0]], [-v[1], v[0], 0]])
    return np.eye(3) + vx + vx @ vx / (1 + c)


def hamiltonian_paths(n, adj):
    paths = []

    def extend(path, seen):
        if len(path) == n:
            paths.append(tuple(path))
            return
        for w in adj[path[-1]]:
            if w not in seen:
                seen.add(w)
                path.append(w)
                extend(path, seen)
                path.pop()
                seen.remove(w)

    for s in range(n):
        extend([s], {s})
    return paths


def geometric_symmetries(x, edges):
    """Vertex permutations that preserve the contact graph and are realised by an orthogonal map."""
    n = len(x)
    adj = {i: set() for i in range(n)}
    for a, b in edges:
        adj[a].add(b)
        adj[b].add(a)
    gram = x @ x.T
    syms = []

    # backtracking graph-automorphism search, pruned by the Gram matrix (isometry test)
    def search(perm):
        k = len(perm)
        if k == n:
            syms.append(tuple(perm))
            return
        for c in range(n):
            if c in perm or len(adj[c]) != len(adj[k]):
                continue
            if all(abs(gram[k, j] - gram[c, perm[j]]) < 1e-4 for j in range(k)):
                perm.append(c)
                search(perm)
                perm.pop()

    search([])
    return syms


def canonical(path, syms):
    forms = []
    for s in syms:
        p = tuple(s[v] for v in path)
        forms.append(p)
        forms.append(p[::-1])
    return min(forms)


def substance(x, edges, path):
    names = [f"v{i:02d}" for i in range(len(x))]
    lines = ["-- generated by glyphs.py", f"-- path: {' -> '.join(names[v] for v in path)}", ""]
    lines.append("Vertex " + ", ".join(names))
    lines.append("")
    for i, (a, b, c) in enumerate(x):
        lines.append(f"At({names[i]}, {a:.6f}, {b:.6f}, {c:.6f})")
    lines.append("")
    for a, b in edges:
        lines.append(f"Contact({names[a]}, {names[b]})")
    lines.append("")
    lines.append(f"Start({names[path[0]]})")
    lines.append(f"End({names[path[-1]]})")
    for a, b in zip(path, path[1:]):
        lines.append(f"Step({names[a]}, {names[b]})")
    return "\n".join(lines) + "\n"


def orient(x):
    """Rotate the configuration into the canonical frame used by every style."""
    # put the biggest hole at the south pole, so the projection keeps every vertex near the centre
    x = x @ rotation_to_south(largest_hole(x)).T
    # fix the spin about the pole: the vertex nearest the north pole points "up" the page
    top = np.argmax(x[:, 2])
    ang = np.arctan2(x[top, 0], x[top, 1])
    rz = np.array([[np.cos(ang), -np.sin(ang), 0], [np.sin(ang), np.cos(ang), 0], [0, 0, 1]])
    return x @ rz.T


def distinct_glyphs(x, edges):
    """Return (directed paths, symmetries, distinct canonical glyphs)."""
    n = len(x)
    adj = {i: [] for i in range(n)}
    for a, b in edges:
        adj[a].append(b)
        adj[b].append(a)
    paths = hamiltonian_paths(n, adj)
    syms = geometric_symmetries(x, edges)
    distinct = sorted({canonical(p, syms) for p in paths})
    return paths, syms, distinct


def main(src, outdir, limit=24):
    with open(src) as f:
        data = json.load(f)
    x = orient(np.array(data["points"]))
    edges = [tuple(e) for e in data["edges"]]

    paths, syms, distinct = distinct_glyphs(x, edges)
    print(f"directed Hamiltonian paths: {len(paths)}")
    print(f"symmetries of the configuration: {len(syms)}")
    print(f"distinct glyphs (up to symmetry and reversal): {len(distinct)}")

    os.makedirs(outdir, exist_ok=True)
    rng = np.random.default_rng(13)
    chosen = sorted(rng.choice(len(distinct), size=min(limit, len(distinct)), replace=False))
    for idx in chosen:
        with open(os.path.join(outdir, f"glyph-{idx:04d}.substance"), "w", newline="\n") as f:
            f.write(substance(x, edges, distinct[idx]))
    with open(os.path.join(outdir, "glyphs.json"), "w", newline="\n") as f:
        json.dump({"points": x.tolist(), "edges": edges, "glyphs": [list(p) for p in distinct]}, f)
    print(f"wrote {len(chosen)} substance files to {outdir}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 24)
