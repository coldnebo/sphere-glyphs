"""Loop glyphs: closed surface loops, and the star loops they generate.

A surface loop is a Hamiltonian cycle on the contact graph: a closed stroke through all
13 points along minimum-distance arcs. Up to the configuration's 8 symmetries (and the
loop's starting point and direction) there are only three.

Each surface loop L is also an ordering of the 13 points, so it can play the role the
13th roots of unity play for the star polygon {13/k}: visit L[0], L[k], L[2k], ... (mod 13).
k = 1 is the surface loop itself; k = 2..6 cut chords through the sphere's interior
(k and 13-k give the same loop reversed). That's a 3 x 6 table of distinct glyphs, and it
generalises stars.py, whose ordering (ring by ring, by azimuth) is not a surface loop.

usage: python3 src/loops.py examples/glyphs/glyphs.json examples/loops
"""
import json
import os
import sys

import numpy as np

import glyphs
from substance_text import at_lines, vertex_names

ROWS = "ABC"


def surface_loops(x, edges):
    """Distinct Hamiltonian cycles on the contact graph, canonical up to symmetry."""
    n = len(x)
    adj = {i: set() for i in range(n)}
    for a, b in edges:
        adj[a].add(b)
        adj[b].add(a)
    paths, syms, _ = glyphs.distinct_glyphs(x, edges)
    cycles = [p for p in paths if p[0] == 0 and p[-1] in adj[0]]
    return sorted({canonical_loop(c, syms) for c in cycles}), syms


def canonical_loop(cycle, syms):
    """Smallest rotation/reflection/symmetry image of a closed loop, starting at vertex 0."""
    forms = []
    for s in syms:
        q = [s[v] for v in cycle]
        for r in (q, q[::-1]):
            i = r.index(0)
            forms.append(tuple(r[i:] + r[:i]))
    return min(forms)


def star(loop, k):
    n = len(loop)
    return [loop[(k * i) % n] for i in range(n)]


def substance(x, cycle, title):
    names = vertex_names(len(x))
    lines = [f"-- name: {title}", "-- generated by loops.py: closed loop, chords through the interior", ""]
    lines.append("Vertex " + ", ".join(names))
    lines.append("")
    lines += at_lines(x)
    lines.append("")
    for a, b in zip(cycle, cycle[1:] + cycle[:1]):
        lines.append(f"Step({names[a]}, {names[b]})")
    return "\n".join(lines) + "\n"


def main(src, outdir):
    with open(src) as f:
        data = json.load(f)
    x = np.array(data["points"])
    edges = [tuple(e) for e in data["edges"]]
    loops, syms = surface_loops(x, edges)
    n = len(x)
    print(f"surface loops (up to symmetry): {len(loops)}")

    os.makedirs(outdir, exist_ok=True)
    seen = set()
    for r, loop in zip(ROWS, loops):
        for k in range(1, (n - 1) // 2 + 1):
            cycle = star(list(loop), k)
            seen.add(canonical_loop(cycle, syms))
            title = f"{r} · k={k}"
            with open(os.path.join(outdir, f"loop-{r}-k{k}.substance"), "w", newline="\n") as f:
                f.write(substance(x, cycle, title))
    print(f"wrote {len(loops) * ((n - 1) // 2)} loop glyphs ({len(seen)} distinct) to {outdir}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
