"""Exactly how many distinct loop glyphs are there?

A loop is a closed path through all 13 points, chords allowed between any two: an undirected
Hamiltonian cycle of the complete graph K13. There are 12!/2 = 239,500,800 of them. Two loops
are the same glyph when one of the configuration's 8 symmetries carries one onto the other.

Burnside's lemma: the number of distinct glyphs is the average number of loops each symmetry
leaves unchanged,

    glyphs = (1/|G|) * sum over g in G of |Fix(g)|.

The identity fixes every loop. Any other g fixes only loops whose chord set g maps onto itself,
so such a loop is a union of whole orbits of chords under <g>. `invariant_cycles` searches
those unions directly, which is small, instead of the 240 million loops.

usage: python3 src/burnside.py examples/glyphs/glyphs.json
"""
import json
import math
import sys
from itertools import combinations

import numpy as np

import glyphs


def edge_orbits(n, perm):
    """Orbits of the edges of K_n under the cyclic group generated by perm."""
    seen, orbits = set(), []
    for e in combinations(range(n), 2):
        if e in seen:
            continue
        orbit, cur = [], e
        while cur not in seen:
            seen.add(cur)
            orbit.append(cur)
            a, b = perm[cur[0]], perm[cur[1]]
            cur = (min(a, b), max(a, b))
        orbits.append(orbit)
    return orbits


def invariant_cycles(n, perm):
    """All undirected Hamiltonian cycles of K_n mapped to themselves by perm (as edge sets)."""
    orbits = edge_orbits(n, perm)
    # orbits usable at all: a cycle has degree 2 everywhere, so an orbit that puts 3+ edges
    # on one vertex can never be part of one
    def degrees(orbit):
        d = [0] * n
        for a, b in orbit:
            d[a] += 1
            d[b] += 1
        return d

    usable = [(o, degrees(o)) for o in orbits if max(degrees(o)) <= 2]
    at = [[i for i, (o, d) in enumerate(usable) if d[v]] for v in range(n)]
    found = []

    def find(parent, x):
        while parent[x] != x:
            x = parent[x]
        return x

    def search(deg, parent, chosen, nedges, v, lo):
        if nedges == n:
            if all(d == 2 for d in deg):
                found.append(frozenset(e for i in chosen for e in usable[i][0]))
            return
        # the smallest vertex still short of degree 2; its remaining orbits are taken in
        # increasing index order, so every edge set is generated exactly once
        while v < n and deg[v] == 2:
            v, lo = v + 1, 0
        if v == n:
            return
        for i in at[v]:
            if i < lo:
                continue
            o, d = usable[i]
            if any(deg[u] + d[u] > 2 for u in range(n)):
                continue
            # adding the orbit's edges must not close a cycle early
            p = parent[:]
            ok = True
            for k, (a, b) in enumerate(o):
                ra, rb = find(p, a), find(p, b)
                if ra == rb and not (nedges + len(o) == n and k == len(o) - 1):
                    ok = False
                    break
                p[ra] = rb
            if not ok:
                continue
            search([deg[u] + d[u] for u in range(n)], p, chosen + [i], nedges + len(o), v, i + 1)

    search([0] * n, list(range(n)), [], 0, 0, 0)
    return found


def count(points, edges):
    syms = glyphs.geometric_symmetries(np.array(points), [tuple(e) for e in edges])
    n = len(points)
    total = math.factorial(n - 1) // 2
    identity = tuple(range(n))
    fix, symmetric = {}, set()
    for g in syms:
        if g == identity:
            fix[g] = total
            continue
        cycles = invariant_cycles(n, g)
        fix[g] = len(cycles)
        symmetric.update(cycles)
    s = sum(fix.values())
    assert s % len(syms) == 0, "Burnside sum must divide evenly"
    glyph_count = s // len(syms)
    # loops with no symmetry fall into orbits of exactly |G|; the rest are symmetric glyphs
    asymmetric_glyphs = (total - len(symmetric)) // len(syms)
    return {
        "loops": total,
        "symmetries": len(syms),
        "fixed": {"".join(f"{v:x}" for v in g): c for g, c in fix.items()},
        "glyphs": glyph_count,
        "symmetric_loops": len(symmetric),
        "symmetric_glyphs": glyph_count - asymmetric_glyphs,
    }


if __name__ == "__main__":
    with open(sys.argv[1]) as f:
        d = json.load(f)
    r = count(d["points"], d["edges"])
    print(f"loops through {len(d['points'])} points:  {r['loops']:,}")
    print(f"symmetries of the configuration: {r['symmetries']}")
    for g, c in r["fixed"].items():
        print(f"  {g}  fixes {c:,} loops")
    print(f"distinct glyphs (Burnside):  {r['glyphs']:,}")
    print(f"  of which symmetric:        {r['symmetric_glyphs']:,}  ({r['symmetric_loops']:,} loops)")
    print(f"  12!/2/8 estimate:          {r['loops'] / r['symmetries']:,.0f}")
